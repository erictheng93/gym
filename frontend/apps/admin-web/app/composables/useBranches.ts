import { useFetch } from '~/composables/core/useFetch'
import { MESSAGES } from '~/constants'
import { useErrorHandler } from '~/composables/core/useErrorHandler'
import { apiErrorMessage } from '~/utils/api-error'
import type { ApiEmployee } from '~/composables/useEmployees'

// =============================================================================
// Wire format of the staff branches API (backend/src/routes/branches.ts):
// camelCase rows; `status` is 'published' (the column default, a live branch) or
// 'archived'; the list rows and the detail row carry `stats`, the detail row `employees`.
// =============================================================================

export type BranchStatus = 'published' | 'archived'

export interface ApiBranch {
  id: string
  status: BranchStatus | null
  createdAt: string
  updatedAt: string
  name: string
  code: string
  type: 'HEADQUARTER' | 'BRANCH'
  address: string | null
  phone: string | null
  taxId: string | null
  settings: Record<string, unknown> | null
  tenantId: string
  stats?: { employeeCount: number; memberCount: number }
}

/** Body of POST /api/branches (createBranchSchema); the branch code is generated by the server */
export interface CreateBranchInput {
  name: string
  type: 'HEADQUARTER' | 'BRANCH'
  address?: string | null
  phone?: string | null
  taxId?: string | null
  status?: BranchStatus
}

export type UpdateBranchInput = Partial<CreateBranchInput>

/** A branch is live unless archived (a null status counts as live, like the column default) */
export const isBranchActive = (branch: Pick<ApiBranch, 'status'>) => branch.status !== 'archived'

let inFlightBranchesPromise: Promise<void> | null = null
const inFlightSingleBranchMap = new Map<string, Promise<ApiBranch | null>>()
const inFlightBranchEmployeesMap = new Map<string, Promise<ApiEmployee[]>>()

export const useBranches = () => {
  const { apiFetch } = useFetch()
  const { handleError } = useErrorHandler()
  const branches = useState<ApiBranch[]>('branches', () => [])
  const isLoading = useState('branches_loading', () => false)

  const fetchBranches = async (includeArchived = false, force = false) => {
    if (!force && inFlightBranchesPromise) {
      return inFlightBranchesPromise
    }

    inFlightBranchesPromise = (async () => {
      isLoading.value = true
      try {
        // the endpoint has no status filter and returns every branch of the tenant
        const { data } = await apiFetch<ApiBranch[]>('/branches')
        const all = data || []
        branches.value = includeArchived ? all : all.filter(isBranchActive)
      } catch (error) {
        handleError(error, {
          context: 'useBranches.fetchBranches',
          customMessage: MESSAGES.ERRORS.BRANCH_FETCH_FAILED
        })
        branches.value = []
      } finally {
        isLoading.value = false
        inFlightBranchesPromise = null
      }
    })()

    return inFlightBranchesPromise
  }

  const fetchBranch = async (id: string, force = false): Promise<ApiBranch | null> => {
    if (!force && inFlightSingleBranchMap.has(id)) {
      return inFlightSingleBranchMap.get(id)!
    }

    const promise = (async () => {
      try {
        const { data } = await apiFetch<ApiBranch>(`/branches/${id}`)
        return data ?? null
      } catch (error) {
        handleError(error, {
          context: 'useBranches.fetchBranch',
          customMessage: MESSAGES.ERRORS.BRANCH_FETCH_FAILED
        })
        return null
      } finally {
        inFlightSingleBranchMap.delete(id)
      }
    })()

    inFlightSingleBranchMap.set(id, promise)
    return promise
  }

  const fetchBranchEmployees = async (branchId: string, force = false): Promise<ApiEmployee[]> => {
    if (!force && inFlightBranchEmployeesMap.has(branchId)) {
      return inFlightBranchEmployeesMap.get(branchId)!
    }

    const promise = (async () => {
      try {
        const { data } = await apiFetch<ApiEmployee[]>('/employees', {
          params: { branchId, status: 'ACTIVE' }
        })
        return data || []
      } catch (error) {
        handleError(error, {
          context: 'useBranches.fetchBranchEmployees',
          customMessage: MESSAGES.ERRORS.EMPLOYEE_FETCH_FAILED
        })
        return []
      } finally {
        inFlightBranchEmployeesMap.delete(branchId)
      }
    })()

    inFlightBranchEmployeesMap.set(branchId, promise)
    return promise
  }

  /** Returns null on failure, after showing the backend's reason; never throws. */
  const createBranch = async (input: CreateBranchInput): Promise<ApiBranch | null> => {
    try {
      const { data } = await apiFetch<ApiBranch>('/branches', { method: 'POST', body: input })
      if (!data) throw new Error(MESSAGES.ERRORS.BRANCH_CREATE_FAILED)
      await fetchBranches()
      return data
    } catch (error) {
      handleError(error, {
        context: 'useBranches.createBranch',
        customMessage: apiErrorMessage(error, MESSAGES.ERRORS.BRANCH_CREATE_FAILED)
      })
      return null
    }
  }

  /** Returns null on failure, after showing the backend's reason; never throws. */
  const updateBranch = async (id: string, input: UpdateBranchInput): Promise<ApiBranch | null> => {
    try {
      const { data } = await apiFetch<ApiBranch>(`/branches/${id}`, { method: 'PATCH', body: input })
      if (!data) throw new Error(MESSAGES.ERRORS.BRANCH_UPDATE_FAILED)
      await fetchBranches()
      return data
    } catch (error) {
      handleError(error, {
        context: 'useBranches.updateBranch',
        customMessage: apiErrorMessage(error, MESSAGES.ERRORS.BRANCH_UPDATE_FAILED)
      })
      return null
    }
  }

  /** The backend archives the branch. Returns false on failure (HQ, branch with employees, 403), after showing why. */
  const deleteBranch = async (id: string): Promise<boolean> => {
    try {
      await apiFetch(`/branches/${id}`, { method: 'DELETE' })
      await fetchBranches()
      return true
    } catch (error) {
      handleError(error, {
        context: 'useBranches.deleteBranch',
        customMessage: apiErrorMessage(error, MESSAGES.ERRORS.BRANCH_DELETE_FAILED)
      })
      return false
    }
  }

  return {
    branches,
    isLoading,
    fetchBranches,
    fetchBranch,
    fetchBranchEmployees,
    createBranch,
    updateBranch,
    deleteBranch
  }
}
