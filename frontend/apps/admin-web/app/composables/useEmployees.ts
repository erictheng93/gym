import { useFetch } from '~/composables/core/useFetch'
import { MESSAGES } from '~/constants'
import { useErrorHandler } from '~/composables/core/useErrorHandler'
import { apiErrorMessage } from '~/utils/api-error'
import type { Employee } from '~/types/schema'

// =============================================================================
// Wire format of the staff employees API (backend/src/routes/employees.ts):
// camelCase rows with `status` (not employment_status), the joined jobTitle / branch
// as {id, name}, and decimal basicSalary as a string.
// =============================================================================

export type EmploymentStatus = 'ACTIVE' | 'RESIGNED' | 'LEAVE'
export type EmploymentType = 'FULL_TIME' | 'PART_TIME' | 'FREELANCE'
/** module -> action -> allowed */
export type PermissionMatrix = Record<string, Record<string, boolean>>

export interface ApiEmployee {
  id: string
  userId: string | null
  branchId: string | null
  jobTitleId: string | null
  employeeCode: string
  fullName: string
  phone: string | null
  email: string | null
  status: EmploymentStatus
  employmentType: EmploymentType
  hireDate: string | null
  resignDate: string | null
  basicSalary: string | number | null
  customPermissions: PermissionMatrix | null
  createdAt: string
  updatedAt: string
  tenantId: string
  jobTitle?: { id: string; name: string; permissionsConfig?: PermissionMatrix | null } | null
  branch?: { id: string; name: string } | null
}

/**
 * The list state also carries the legacy snake_case fields that other pages still read
 * (full_name, employee_code, ...). The API never sends them, so those reads are undefined
 * at runtime; they are typed here only so the not-yet-migrated pages keep compiling.
 */
export type EmployeeListItem = ApiEmployee & Pick<Employee,
  'employee_code' | 'full_name' | 'user_id' | 'branch_id' | 'job_title_id' | 'supervisor_id' | 'hire_date'
  | 'employment_status' | 'employment_type' | 'basic_salary' | 'custom_permissions' | 'job_title' | 'supervisor'>

/** Body of POST /api/employees (createEmployeeSchema); the employee code is generated by the server */
export interface CreateEmployeeInput {
  fullName: string
  branchId: string
  jobTitleId: string
  employmentType: EmploymentType
  phone?: string | null
  email?: string | null
  status?: EmploymentStatus
  hireDate?: string | null
  basicSalary?: number | null
}

/** Body of PATCH /api/employees/:id (updateEmployeeSchema); every field optional */
export type UpdateEmployeeInput = Partial<CreateEmployeeInput> & {
  customPermissions?: PermissionMatrix | null
}

/** GET /api/employees; `meta` is present only when `page` was requested */
interface EmployeeListResponse {
  success: boolean
  data: ApiEmployee[]
  meta?: { total: number; page: number; limit: number; totalPages: number }
}

const inFlightEmployeesMap = new Map<string, Promise<void>>()
const inFlightSingleEmployeeMap = new Map<string, Promise<ApiEmployee | null>>()
let inFlightAllEmployeesPromise: Promise<Employee[]> | null = null

export const useEmployees = () => {
  const { apiFetch } = useFetch()
  const { handleError } = useErrorHandler()
  const employees = useState<EmployeeListItem[]>('employees', () => [])
  const isLoading = useState('employees_loading', () => false)
  const totalCount = useState('employees_total', () => 0)

  const fetchEmployees = async (options?: {
    page?: number
    limit?: number
    search?: string
    branchId?: string
    status?: string
    jobTitleId?: string
  }, force = false) => {
    const key = JSON.stringify(options || {})
    if (!force && inFlightEmployeesMap.has(key)) {
      return inFlightEmployeesMap.get(key)
    }

    const promise = (async () => {
      isLoading.value = true
      const { page = 1, limit = 20, search, branchId, status, jobTitleId } = options || {}

      try {
        const response = await apiFetch<ApiEmployee[]>('/employees', {
          params: { page, limit, search, branchId, status, jobTitleId }
        }) as unknown as EmployeeListResponse

        employees.value = (response.data || []) as EmployeeListItem[]
        totalCount.value = Number(response.meta?.total ?? employees.value.length)
      } catch (error) {
        handleError(error, {
          context: 'useEmployees.fetchEmployees',
          customMessage: MESSAGES.ERRORS.EMPLOYEE_FETCH_FAILED
        })
        employees.value = []
        totalCount.value = 0
      } finally {
        isLoading.value = false
        inFlightEmployeesMap.delete(key)
      }
    })()

    inFlightEmployeesMap.set(key, promise)
    return promise
  }

  const getEmployee = async (id: string) => {
    const existing = inFlightSingleEmployeeMap.get(id)
    if (existing) {
      return existing
    }

    const promise = (async () => {
      try {
        const { data } = await apiFetch<ApiEmployee>(`/employees/${id}`)
        return data ?? null
      } catch (error) {
        handleError(error, {
          context: 'useEmployees.getEmployee',
          customMessage: MESSAGES.ERRORS.EMPLOYEE_FETCH_FAILED
        })
        return null
      } finally {
        inFlightSingleEmployeeMap.delete(id)
      }
    })()

    inFlightSingleEmployeeMap.set(id, promise)
    return promise
  }

  /** Returns null on failure, after showing the backend's reason; never throws. */
  const createEmployee = async (input: CreateEmployeeInput): Promise<ApiEmployee | null> => {
    try {
      const { data } = await apiFetch<ApiEmployee>('/employees', { method: 'POST', body: input })
      if (!data) throw new Error(MESSAGES.ERRORS.EMPLOYEE_CREATE_FAILED)
      return data
    } catch (error) {
      handleError(error, {
        context: 'useEmployees.createEmployee',
        customMessage: apiErrorMessage(error, MESSAGES.ERRORS.EMPLOYEE_CREATE_FAILED)
      })
      return null
    }
  }

  /** Returns null on failure, after showing the backend's reason; never throws. */
  const updateEmployee = async (id: string, input: UpdateEmployeeInput): Promise<ApiEmployee | null> => {
    try {
      const { data } = await apiFetch<ApiEmployee>(`/employees/${id}`, { method: 'PATCH', body: input })
      if (!data) throw new Error(MESSAGES.ERRORS.EMPLOYEE_UPDATE_FAILED)
      return data
    } catch (error) {
      handleError(error, {
        context: 'useEmployees.updateEmployee',
        customMessage: apiErrorMessage(error, MESSAGES.ERRORS.EMPLOYEE_UPDATE_FAILED)
      })
      return null
    }
  }

  /** The backend archives the employee (status RESIGNED). Returns false on failure, after showing why. */
  const deleteEmployee = async (id: string): Promise<boolean> => {
    try {
      await apiFetch(`/employees/${id}`, { method: 'DELETE' })
      return true
    } catch (error) {
      handleError(error, {
        context: 'useEmployees.deleteEmployee',
        customMessage: apiErrorMessage(error, MESSAGES.ERRORS.EMPLOYEE_DELETE_FAILED)
      })
      return false
    }
  }

  // 取得所有在職員工（用於下拉選單）
  // Typed as the legacy snake_case Employee only so the other pages that still read full_name /
  // employee_code keep compiling; the rows really are ApiEmployee (camelCase), see the note in the report.
  const fetchAllEmployees = async () => {
    if (inFlightAllEmployeesPromise) {
      return inFlightAllEmployeesPromise
    }

    inFlightAllEmployeesPromise = (async () => {
      try {
        // no `page` param: the backend returns the full list
        const { data } = await apiFetch<ApiEmployee[]>('/employees', { params: { status: 'ACTIVE' } })
        return (data || []) as unknown as Employee[]
      } catch (error) {
        handleError(error, {
          context: 'useEmployees.fetchAllEmployees',
          customMessage: MESSAGES.ERRORS.EMPLOYEE_FETCH_FAILED,
          showToast: false
        })
        return []
      } finally {
        inFlightAllEmployeesPromise = null
      }
    })()

    return inFlightAllEmployeesPromise
  }

  return {
    employees,
    isLoading,
    totalCount,
    fetchEmployees,
    getEmployee,
    createEmployee,
    updateEmployee,
    deleteEmployee,
    fetchAllEmployees
  }
}
